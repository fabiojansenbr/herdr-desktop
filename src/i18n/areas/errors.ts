// Errors area (spec 071, PRD i18n P3). The host composes every `RuntimeError.message` in English
// (AC-071-01); this is the table `errorText({code, message})` of the 067 base reads to say the
// same thing in the user's language. One key per `code`, so the WebView never parses a message.
//
// The `en` value of a key is the wording the host sends for that code, and `pt` is the wording
// this product showed before the migration — that is what keeps the existing Portuguese
// assertions of the suite true. A code whose host message carries a measured fact (a method, a
// version, a limit, a deadline) keeps the sentence and drops the fact: `errorText` takes no
// parameters, and the code is what identifies the failure.
//
// Codes deliberately absent, so the engine's own words survive: `endpoint_error` and
// `events_error`, whose message *is* the text the engine sent.
//
// `dialog.openProject` lives here because 071 also owns the native folder picker title
// (AC-071-03): the front sends it already translated, the host only validates it.

